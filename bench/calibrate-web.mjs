#!/usr/bin/env node
// Which web rules report findings and which report places to read.
//
// A rule that matches a dangerous call without seeing where its value comes from fires on every
// such call. Two measurements say what that is worth: how often it stood where a real bug was
// fixed (bench/injection.mjs, the tune half only) and how often it fires on applications that
// are presumed fine (bench/noise.mjs, all corpora). A rule that fires at least MIN times on the
// applications and more than RATIO times for every real bug it pointed at reports places.
//
//   node bench/calibrate-web.mjs --injection bench/results/<date>-injection.json --noise bench/results/<date>-noise/
//   node bench/calibrate-web.mjs ... --write      # also write skills/vetcode/scripts/lib/data/web-places.json
//
// Only rules of the classes the injection benchmark covers are judged; the others keep reporting findings.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { kindOfRule } from "../skills/vetcode/scripts/lib/sinks.mjs";

const argv = process.argv, arg = (k, d) => { const i = argv.indexOf(k); return i > 0 ? argv[i + 1] : d; };
const here = path.dirname(fileURLToPath(import.meta.url));
const MIN = +arg("--min", 10), RATIO = +arg("--ratio", 20);
// An entry of the catalogue of dangerous calls is a place by nature; it is dropped when it fires at
// least DROP times on the applications and never stood where a real bug was fixed.
const DROP = +arg("--drop", 40);
const isSink = id => id.startsWith("sink-");
const injection = JSON.parse(fs.readFileSync(arg("--injection"), "utf8"));
const dir = arg("--noise");
const noise = {}; let repos = 0;
for (const f of fs.readdirSync(dir).filter(f => f.endsWith(".json"))) for (const r of JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")).repos) {
  repos++;
  for (const [k, v] of [...Object.entries(r.rules || {}), ...Object.entries(r.placeRules || {})]) noise[k] = (noise[k] || 0) + v;
}
const hits = injection.ruleHitsOnTune || {};
const rows = [...new Set([...Object.keys(noise), ...Object.keys(hits)])].filter(k => kindOfRule(k) && !isSink(k)).map(k => ({ rule: k, hits: hits[k] || 0, noise: noise[k] || 0 }))
  .map(r => ({ ...r, place: r.noise >= MIN && r.noise > RATIO * r.hits })).sort((a, b) => b.noise - a.noise);
const sinks = [...new Set([...Object.keys(noise), ...Object.keys(hits)])].filter(isSink).map(k => ({ rule: k, hits: hits[k] || 0, noise: noise[k] || 0 }))
  .map(r => ({ ...r, dropped: r.noise >= DROP && r.hits === 0 })).sort((a, b) => b.noise - a.noise);
console.log(`${injection.tune.cases} real bugs (tune half), ${repos} applications. A rule reports places when it fires at least ${MIN} times on the applications and more than ${RATIO} times per real bug it pointed at.\n`);
console.log("| Rule | Pointed at a real bug | Fires on the applications | Reports |\n|---|---|---|---|");
for (const r of rows) console.log(`| ${r.rule} | ${r.hits} | ${r.noise} | ${r.place ? "places" : "findings"} |`);
console.log(`\nThe catalogue of dangerous calls. An entry is dropped when it fires at least ${DROP} times on the applications and never stood where a real bug was fixed.\n`);
console.log("| Entry | Stood where a real bug was fixed | Fires on the applications | |\n|---|---|---|---|");
for (const r of sinks) console.log(`| ${r.rule} | ${r.hits} | ${r.noise} | ${r.dropped ? "dropped" : "kept"} |`);
const places = rows.filter(r => r.place).map(r => r.rule).sort();
const dropped = sinks.filter(r => r.dropped).map(r => r.rule).sort();
if (argv.includes("--write")) {
  const out = path.join(here, "../skills/vetcode/scripts/lib/data/web-places.json");
  fs.writeFileSync(out, JSON.stringify({ note: "Generated by bench/calibrate-web.mjs. Rules that report places to read, not findings.", min: MIN, ratio: RATIO, places, drop: DROP, dropped }, null, 1) + "\n");
  console.log(`\nWrote ${places.length} rules that report places and ${dropped.length} dropped catalogue entries to ${path.relative(process.cwd(), out)}.`);
}
