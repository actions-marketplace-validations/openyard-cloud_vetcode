#!/usr/bin/env node
// Which rules have earned the right to give a verdict by themselves?
//
//   node bench/calibrate.mjs <benchmark result.json>... [--apps bench/app-first-look.json]
//                            [--out skills/vetcode/scripts/lib/data/rule-trust.json]
//
// A scanner made of several hundred rules, each allowed to call a target malicious on its own,
// is wrong somewhere on almost any large code base: every wrong verdict we have seen on a clean
// app came from one rule matching one or two lines. So a verdict needs either a rule with a
// record, or two different rules pointing at the same file. This script reads the record.
//
// For each rule the benchmark counts the samples it helped flag and the ones it flagged alone,
// malicious and clean (bench/run.mjs, ruleStats). Clean apps where a rule was the reason for a
// wrong verdict at first look are added to its clean count (--apps). A rule decides alone when
//   - it flagged at least MIN_ALONE malicious samples alone and at most MAX_WRONG of what it
//     flagged alone was clean, or
//   - it rarely stands alone, but fired on at least MIN_SEEN malicious samples and on no clean one.
// Every other rule, and every rule written after the last calibration, is a sign: it is
// reported in full, and it takes a second sign in the same file to make a verdict.
//
// Calibrate on one sample (seed 7, the Datadog skills) and check on another (seed 31, the
// held-out skills): the check is what says whether the table generalises.
import fs from "node:fs";
import path from "node:path";

const MIN_ALONE = 5, MAX_WRONG = 0.10, MIN_SEEN = 20;
const argv = process.argv.slice(2), opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
const out = opt("--out"), appsFile = opt("--apps");
const files = argv.filter((a, i) => !a.startsWith("--") && !["--out", "--apps"].includes(argv[i - 1]));
const stats = {};
for (const f of files) for (const r of JSON.parse(fs.readFileSync(f, "utf8")).results) for (const [rule, s] of Object.entries(r.ruleStats || {})) {
  const t = stats[rule] ||= { malicious: 0, maliciousAlone: 0, benign: 0, benignAlone: 0, apps: 0 };
  for (const k of ["malicious", "maliciousAlone", "benign", "benignAlone"]) t[k] += s[k] || 0;
}
if (appsFile) for (const [rule, n] of Object.entries(JSON.parse(fs.readFileSync(appsFile, "utf8")).rules)) (stats[rule] ||= { malicious: 0, maliciousAlone: 0, benign: 0, benignAlone: 0, apps: 0 }).apps += n;

const decides = [], rows = [];
for (const [rule, s] of Object.entries(stats).sort((a, b) => b[1].maliciousAlone - a[1].maliciousAlone || b[1].malicious - a[1].malicious)) {
  const wrong = s.benignAlone + s.apps;
  const ok = s.maliciousAlone >= MIN_ALONE ? wrong / (s.maliciousAlone + wrong) <= MAX_WRONG : s.malicious >= MIN_SEEN && s.benign + s.apps === 0;
  if (ok) decides.push(rule);
  rows.push(`${ok ? "decides" : "sign   "} ${rule.padEnd(34)} malicious ${String(s.malicious).padStart(5)} (alone ${String(s.maliciousAlone).padStart(3)})  clean ${String(s.benign).padStart(3)} (alone ${String(s.benignAlone).padStart(2)}, apps ${s.apps})`);
}
console.log(rows.join("\n"));
console.log(`\n${decides.length} rules decide alone, ${rows.length - decides.length} are signs.`);
if (out) {
  fs.writeFileSync(out, JSON.stringify({ about: "Rules that may give a verdict alone; generated by bench/calibrate.mjs, do not edit by hand.", criteria: { minAlone: MIN_ALONE, maxWrong: MAX_WRONG, minSeen: MIN_SEEN }, from: files.map(f => path.basename(path.dirname(f)) + "/" + path.basename(f)), decides: decides.sort() }, null, 1) + "\n");
  console.log(`written: ${out}`);
}
